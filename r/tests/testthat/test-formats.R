test_that("formats are detected from the extension", {
  expect_equal(detect_format("a/b.csv"), "csv")
  expect_equal(detect_format("a/b.CSV.GZ"), "csv")
  expect_equal(detect_format("b.tsv"), "tsv")
  expect_equal(detect_format("b.json"), "json")
  expect_equal(detect_format("b.geojson"), "geojson")
  expect_equal(detect_format("b.parquet"), "parquet")
  expect_equal(detect_format("b.rds"), "rds")
  expect_equal(detect_format("b.xlsx"), "xlsx")
  expect_equal(detect_format("b.md"), "text")
  expect_equal(detect_format("b.png"), NA_character_)
  expect_equal(file_extension("x/y.csv.gz"), ".csv.gz")
  expect_equal(file_extension("x/y.JSON"), ".json")
  expect_equal(file_extension("noext"), "")
})

test_that("data frames travel as csv, csv.gz, tsv, parquet and rds", {
  fake <- local_fake_s3()
  cfg <- fake_config()
  df <- data.frame(x = c(1.5, 2), y = c("a", "bç"), stringsAsFactors = FALSE)

  write_s3(df, "d.csv", config = cfg)
  expect_equal(as.data.frame(read_s3("d.csv", config = cfg)), df)
  write_s3(df, "d.csv.gz", config = cfg)
  expect_equal(fake$state$objects[["test/d.csv.gz"]]$type, "application/gzip")
  expect_equal(as.data.frame(read_s3("d.csv.gz", config = cfg)), df)
  write_s3(df, "d.tsv", config = cfg)
  expect_equal(as.data.frame(read_s3("d.tsv", config = cfg)), df)
  write_s3(df, "d.rds", config = cfg)
  expect_equal(read_s3("d.rds", config = cfg), df)
  write_s3(df, "d.bin", format = "rds", config = cfg)
  expect_equal(read_s3("d.bin", format = "rds", config = cfg), df)
  expect_equal(read_s3("d.csv", config = cfg, col_types = "cc")$x, c("1.5", "2"))

  skip_if_not_installed("nanoparquet")
  write_s3(df, "d.parquet", config = cfg)
  expect_equal(as.data.frame(read_s3("d.parquet", config = cfg)), df)
})

test_that("json, text and raw", {
  fake <- local_fake_s3()
  cfg <- fake_config()
  write_s3(list(a = 1, b = c("x", "y")), "j.json", config = cfg)
  expect_equal(rawToChar(fake$state$objects[["test/j.json"]]$data), '{"a":1,"b":["x","y"]}')
  expect_equal(read_s3("j.json", config = cfg), list(a = 1, b = c("x", "y")))
  write_s3(list(a = 1), "p.json", pretty = TRUE, config = cfg)
  expect_match(rawToChar(fake$state$objects[["test/p.json"]]$data), "\n")

  write_s3(c("linha 1", "linha ç"), "t.txt", config = cfg)
  expect_equal(read_s3("t.txt", config = cfg), "linha 1\nlinha ç")
  expect_equal(fake$state$objects[["test/t.txt"]]$type, "text/plain")
  write_s3("sem extensao", "noext", config = cfg)
  expect_equal(fake$state$objects[["test/noext"]]$type, "application/octet-stream")
  expect_equal(read_s3("noext", config = cfg, format = "text"), "sem extensao")

  bytes <- as.raw(c(0, 1, 2, 255))
  write_s3(bytes, "b.png", config = cfg)
  expect_equal(read_s3("b.png", config = cfg), bytes)
  expect_equal(fake$state$objects[["test/b.png"]]$type, "image/png")

  expect_error(write_s3(data.frame(a = 1), "noext", config = cfg), class = "s3pe_error_input")
  expect_error(write_s3(1:3, "x.txt", config = cfg), class = "s3pe_error_input")
  expect_error(write_s3("x", "x.bin", format = "raw", config = cfg), class = "s3pe_error_input")
  expect_error(write_s3(data.frame(a = 1), "x.xlsx", config = cfg), class = "s3pe_error_input")
  expect_error(read_s3("b.png", format = "nope", config = cfg))
})

test_that("geojson falls back to jsonlite without sf and uses sf with it", {
  fake <- local_fake_s3()
  cfg <- fake_config()
  gj <- '{"type":"FeatureCollection","features":[{"type":"Feature","properties":{"nome":"Recife"},"geometry":{"type":"Point","coordinates":[-34.9,-8.05]}}]}'
  write_s3(charToRaw(gj), "pe.geojson", format = "raw", config = cfg)
  expect_equal(fake$state$objects[["test/pe.geojson"]]$type, "application/geo+json")
  expect_equal(read_s3("pe.geojson", format = "json", config = cfg)$type, "FeatureCollection")
  skip_if_not_installed("sf")
  x <- read_s3("pe.geojson", config = cfg)
  expect_s3_class(x, "sf")
  expect_equal(x$nome, "Recife")
  write_s3(x, "pe2.geojson", config = cfg)
  expect_equal(read_s3("pe2.geojson", config = cfg)$nome, "Recife")
})
